/** Íconos de una comuna (siempre al menos uno). `own` indica si son propios. */
export function landmarksFor(comuna) {
  const code = comuna.code;
  if (BY_COMUNA[code]) return { own: true, sprites: BY_COMUNA[code].map((id) => SPRITES[id]) };
  let ids = BY_REGION[comuna.region];
  // Gran Santiago: el Metro.
  if (comuna.region === 13 && (Math.floor(code / 100) === 131 || code === 13201 || code === 13401)) ids = ['metro'];
  // Provincia de Chiloé: sus iglesias.
  if (Math.floor(code / 100) === 102) ids = ['iglesia'];
  return { own: false, sprites: ids.map((id) => SPRITES[id]) };
}

const hexCache = new Map();
const rgb = (hex) => {
  let c = hexCache.get(hex);
  if (!c) hexCache.set(hex, (c = [parseInt(hex.slice(1, 3), 16), parseInt(hex.slice(3, 5), 16), parseInt(hex.slice(5, 7), 16)]));
  return c;
};

/** Dibuja un sprite (con sombra) sobre un ImageData. */
export function drawSprite(img, sprite, ox, oy, { shadow = true, scale = 1 } = {}) {
  const { width: W, height: H, data } = img;
  const set = (x, y, c, a = 1) => {
    if (x < 0 || y < 0 || x >= W || y >= H) return;
    const o = (y * W + x) * 4;
    for (let i = 0; i < 3; i++) data[o + i] = Math.round(data[o + i] * (1 - a) + c[i] * a);
    data[o + 3] = 255;
  };
  const k = scale;
  const block = (x, y, c, a) => { for (let dy = 0; dy < k; dy++) for (let dx = 0; dx < k; dx++) set(ox + x * k + dx, oy + y * k + dy, c, a); };
  if (shadow) for (const [x, y] of sprite.px) { for (let dy = 0; dy < k; dy++) for (let dx = 0; dx < k; dx++) set(ox + x * k + dx + k, oy + y * k + dy + k, [20, 16, 30], 0.35); }
  for (const [x, y, hex] of sprite.px) block(x, y, rgb(hex), 1);
}

/** Miniatura del sprite como canvas (para listas). */
export function spriteCanvas(sprite) {
  const c = document.createElement('canvas');
  c.width = 18;
  c.height = 18;
  c.className = 'sprite-canvas';
  const ctx = c.getContext('2d');
  const img = ctx.createImageData(18, 18);
  drawSprite(img, sprite, 1, 1, { shadow: false });
  ctx.putImageData(img, 0, 0);
  return c;
}
