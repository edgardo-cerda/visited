/** Sprites normalizados: { id, name, w, h, px: [[x, y, color], …] }. */
export const SPRITES = Object.fromEntries(Object.entries(ART).map(([id, [name, art]]) => {
  const rows = art.split('\n').filter((r) => r.length).map((r) => r.padEnd(16, '.').slice(0, 16));
  while (rows.length < 16) rows.push('.'.repeat(16));
  const px = [];
  rows.slice(0, 16).forEach((row, y) => [...row].forEach((ch, x) => { if (PAL[ch]) px.push([x, y, PAL[ch]]); }));
  return [id, { id, name, w: 16, h: 16, px }];
}));

